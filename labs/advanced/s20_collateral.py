"""
20회차 실습. 토큰화 MMF를 담보로 쓰면 무엇이 달라지나: 헤어컷, 담보 이동 시간, 필요한 담보 총량.

1. 헤어컷 = 청산 기간(MPOR) 동안 담보 가치가 떨어질 수 있는 폭(99% 분위수) + 처분 비용
     h = z(0.99) · σ_일 · √MPOR + c
   CFTC 직원 지침(25-39, 2025-12-08)은 토큰화 자산의 헤어컷을 기초자산과 같은 위험 기반 방식으로 정하되,
   결제 시간 차이와 신용·시장·유동성 위험 차이를 반영해 조정하라고 했다. 이 모형은 그 '결제 시간'만 MPOR로 바꿔 본다.
2. 담보 이동이 느리면 그 사이를 메울 여유 담보(버퍼)가 필요하다.
     버퍼 ≈ 증거금 요구의 하루 변동 폭(99%) × 이동에 걸리는 일수
   토큰은 주말·야간에도 옮길 수 있어 이동 일수가 짧아진다.
3. 담보 회전(velocity): 같은 담보가 하루에 몇 번 다른 거래에 쓰일 수 있나.

변동성·비용·일수는 모두 가정이다.
실행: python3 s20_collateral.py   (표준 라이브러리만)
"""

import math

Z99 = 2.326

# (이름, 일간 변동성, 처분 비용, MPOR(일))
ASSETS = [
    ("현금(달러)", 0.0, 0.0, 0),
    ("미국 국채 3개월 (기존)", 0.0002, 0.0002, 2),
    ("미국 국채 3개월 (토큰)", 0.0002, 0.0002, 1),
    ("정부 MMF 지분 (기존, 환매 T+1)", 0.00005, 0.0005, 2),
    ("정부 MMF (토큰, 즉시 이전)", 0.00005, 0.0005, 1),
    ("S&P 500 주식", 0.012, 0.001, 2),
    ("비트코인 (24시간 거래)", 0.035, 0.003, 1),
]


def haircut(sigma, cost, mpor):
    return Z99 * sigma * math.sqrt(mpor) + cost


def main():
    print("1. 헤어컷 (99%, h = z·σ·√MPOR + 처분 비용)")
    print(f"   {'담보':<30}{'σ(일)':>8}{'MPOR':>6}{'헤어컷':>9}")
    for name, sg, c, m in ASSETS:
        print(f"   {name:<30}{sg:>8.3%}{m:>6}{haircut(sg, c, m):>9.3%}")
    # 같은 MMF: 기존 지분은 금요일 오후 마진콜에 월요일에야 옮길 수 있다 → 실질 MPOR 4일 가정
    old = haircut(0.00005, 0.0005, 4)
    new = haircut(0.00005, 0.0005, 1)
    print(f"\n   MMF 지분, 주말 끼면 MPOR 4일: {old:.3%}  vs 토큰 1일: {new:.3%}  (차이 {old-new:.3%}p)")
    print("   → 저변동 담보는 헤어컷 차이가 작다. 이득은 헤어컷보다 '이동 시간'에서 나온다.")

    print("\n2. 이동 시간과 여유 담보 (증거금 요구가 하루에 σ_m만큼 출렁인다고 가정)")
    margin = 1_000          # 백만 달러 (10억 달러 증거금)
    sigma_m = 0.08          # 가정: 증거금 요구의 일간 변동 8%
    for days, tag in [(4, "기존: 금요일 콜 → 화요일 도착"), (1, "토큰: 다음 날 이전"), (0.25, "토큰: 몇 시간 안 이전")]:
        buf = Z99 * sigma_m * margin * math.sqrt(days)
        print(f"   {tag:<24} 이동 {days:>4}일  여유 담보 {buf:>6,.0f}백만$ (증거금의 {buf/margin:.0%})")

    print("\n3. 담보 회전: 하루 결제 흐름 F를 처리하는 데 묶이는 담보 = F × (묶이는 시간 / 하루)")
    flow = 10_000           # 하루 100억 달러를 결제 담보로 돌린다
    for hours in [24, 8, 2, 0.5]:
        print(f"   담보 1단위가 {hours:>4}시간씩 묶이면 필요한 담보 {flow*hours/24:>7,.0f}백만$")
    print("\n읽을 것: 토큰화가 바꾸는 것은 담보의 가치가 아니라 담보가 움직이는 시간이다.")
    print("같은 국채·MMF라도 주말·야간에 옮길 수 있으면 여유 담보와 묶이는 담보가 함께 준다.")


if __name__ == "__main__":
    main()
